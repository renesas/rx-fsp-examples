/* Variable to store the user input for DAC conversion */
static int32_t g_inputRead = RESET_VALUE;
/* Flag to notify that ADC read is complete */
static volatile bool g_is_read_complete = false;
/* Flag to notify any error in reading ADC data */
static volatile bool g_error_flag = false;
extern bsp_leds_t g_bsp_leds;

/* Variable to store scanned ADC data */
static uint16_t g_adc_data = RESET_VALUE;
/* Function for ADC calibration on ADC_B version */
static fsp_err_t adc_start_calibration(void);
/* Flag to notify successful calibration completion */
static volatile bool b_is_calibration_complete = false;
/* Function to process the user input */
static fsp_err_t read_process_input_from_RTT(void);
/* Function to process the user input for DAC conversion */
static fsp_err_t dac_adc_operations(int32_t * input);

/* Functions to close opened modules */
static void dac_deinit(void);
static void adc_deinit(void);

/*******************************************************************************************************************//**
 * main() is generated by the RX Configuration editor and is used to generate threads if an RTOS is used. This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void hal_entry(void)
{
    fsp_err_t err = FSP_SUCCESS;
    fsp_pack_version_t version = { RESET_VALUE };

    /* Version get API for FLEX pack information */
    R_FSP_VersionGet(&version);

    R_IOPORT_PinWrite(&g_ioport_ctrl, (bsp_io_port_pin_t) g_bsp_leds.p_leds[ERR_LED],
                     (bsp_io_level_t)BSP_IO_LEVEL_LOW);
#if (USE_VIRTUAL_COM == 1)
    err= TERM_INIT();
    if (FSP_SUCCESS != err)
    {
        /* Turn ON error LED to indicate uart_init failed */
        R_IOPORT_PinWrite(&g_ioport_ctrl, (bsp_io_port_pin_t) g_bsp_leds.p_leds[ERR_LED],
                          (bsp_io_level_t) BSP_IO_LEVEL_HIGH);
        /* Error trap */
        ERROR_TRAP;
    }
#endif
    /* Example Project information printed on the Console */
    APP_PRINT(BANNER_1);
    APP_PRINT(BANNER_2);
    APP_PRINT(BANNER_3, EP_VERSION);
    APP_PRINT(BANNER_4, version.version_id_b.major, version.version_id_b.minor, version.version_id_b.patch);
    APP_PRINT(BANNER_5);
    APP_PRINT(BANNER_6);
    APP_PRINT(EP_INFO);

    /* Open the DAC channel */
    err = R_DAC_B_Open(&g_dac_ctrl, &g_dac_cfg);
    /* Handle error */
    if (FSP_SUCCESS != err)
    {
        /* DAC module open failed */
        APP_ERR_PRINT("\r\n** R_DAC_B_Open API failed **\r\n");
        APP_ERR_TRAP(err);
    }

    /* Open/Initialize ADC module */
    err = R_ADC_B_Open(&g_adc_ctrl, &g_adc_cfg);
    /* Handle error */
    if (FSP_SUCCESS != err)
    {
     /* ADC module open failed */
     dac_deinit();
     /* ADC failure message */
     APP_ERR_PRINT("\r\n** R_ADC_B_Open API failed **\r\n");
     APP_ERR_TRAP(err);
    }

    /* Configures the ADC scan parameters */
    err = R_ADC_B_ScanCfg(&g_adc_ctrl, &g_adc_scan_cfg);
    /* Handle error */
    if (FSP_SUCCESS != err)
    {
        adc_deinit();
        dac_deinit();
        /* ADC failure message */
        APP_ERR_PRINT("\r\n** R_ADC_B_ScanCfg API failed **\r\n");
        APP_ERR_TRAP(err);
    }
    /* Calibrate the ADC */
    err = adc_start_calibration();
    /* Handle error */
    if (FSP_SUCCESS != err)
    {
        adc_deinit();
        dac_deinit();
        /* ADC failure message */
        APP_ERR_PRINT("\r\n** adc_start_calibration failed **\r\n");
        APP_ERR_TRAP(err);
    }
    APP_PRINT("\r\nEnter values for DAC conversion. Input Range: 1 to 4095\r\n");

    while (true)
    {
        if (APP_CHECK_DATA)
        {
            /* Validate input value from the user */
            err = read_process_input_from_RTT ();
            /* Handle error */
            if (FSP_SUCCESS != err)
            {
                /* Notify the user if the input is not valid */
                APP_PRINT("\r\nInvalid Input. Valid Range: 1 to 4095. Please enter valid input.\r\n");
            }
            /* Process valid input from the user */
            else
            {
                err = dac_adc_operations(&g_inputRead);
                /* Handle error */
                if (FSP_SUCCESS != err)
                {
                    adc_deinit();
                    dac_deinit();
                    APP_ERR_PRINT("\r\n** Processing input failed **\r\n");
                    APP_ERR_TRAP(err);
                }
            }
        }

        /* Print read ADC output data */
        if (true == g_is_read_complete)
        {
            g_is_read_complete = false;
            APP_PRINT("\r\nData read from ADC channel: %d\r\n", g_adc_data);
        }
        else if (true == g_error_flag)
        {
            adc_deinit();
            dac_deinit();
            /* ADC failure message */
            APP_ERR_PRINT("\r\n** R_ADC_B_Read failed **\r\n");
            APP_ERR_TRAP(err);
        }
        else
        {
            /* Do nothing */
        }
    }

#if BSP_TZ_SECURE_BUILD
    /* Enter non-secure code */
    R_BSP_NonSecureEnter();
#endif
}

/*******************************************************************************************************************//**
 * @brief       This function reads the user input from RTT and processes it.
 * @param[IN]   None
 * @retval      FSP_SUCCESS     Upon successful of conversion of the user input value.
 * @retval      Any other error code apart from FSP_SUCCESS     Unsuccessful DAC conversion.
 **********************************************************************************************************************/
static fsp_err_t read_process_input_from_RTT(void)
{
    fsp_err_t err = FSP_SUCCESS;

    char readBuff[BUFFER_SIZE_DOWN] = { RESET_VALUE };

    /* Read input value for DAC conversion from the user */
    APP_READ(readBuff);

    /* Convert the input string to an integer value */
    g_inputRead = atoi ((char *) readBuff);

    if ((DAC_MIN_VAL <= g_inputRead) && (DAC_MAX_VAL >= g_inputRead))
    {
        APP_PRINT("\r\nUser input value for DAC conversion: %d\r\n", g_inputRead);
    }
    else
    {
        err = FSP_ERR_INVALID_ARGUMENT;
    }
    return err;
}

/*******************************************************************************************************************//**
 * @brief       This function initiates the ADC calibration
 * @param[IN]   None
 * @retval      FSP_SUCCESS     Upon successful of ADC calibration
 * @retval      Any Other Error code apart from FSP_SUCCESS  Unsuccessful calibration failure
 **********************************************************************************************************************/
static fsp_err_t adc_start_calibration(void)
{
    fsp_err_t err = FSP_SUCCESS;     /* Error status */

    APP_PRINT("\r\nADC Calibration Started\r\n");

    /* Initiate ADC calibration */
    err = R_ADC_B_Calibrate(&g_adc_ctrl, NULL);
    /* Handle error */
    if (FSP_SUCCESS != err)
    {
        APP_ERR_RETURN(err,"\r\n** R_ADC_B_Calibrate API failed **\r\n");
    }
    /* Wait here till the calibration is complete. It takes 24msec to 780msec based on clock */
    while (!b_is_calibration_complete);

    APP_PRINT("\r\nADC Calibration Successful\r\n");
    return err;
}

/*******************************************************************************************************************//**
 * @brief       This function performs DAC conversion and ADC Scan operation
 * @param[IN]   input           The user input for DAC conversion
 * @retval      FSP_SUCCESS     Upon successful of ADC calibration
 * @retval      Any Other Error code apart from FSP_SUCCESS  Unsuccessful DAC conversion or ADC scan
 **********************************************************************************************************************/
static fsp_err_t dac_adc_operations(int32_t * input)
{
    fsp_err_t err = FSP_SUCCESS;     /* Error status */

    /* Write value to DAC module */
    err = R_DAC_B_Write(&g_dac_ctrl, (uint16_t)(* input));
    /* Handle error */
    if (FSP_SUCCESS != err)
    {
        /* DAC Write Failure message */
        APP_ERR_RETURN(err,"\r\n** R_DAC_B_Write API failed **\r\n");
    }

    /* Start DAC conversion */
    err = R_DAC_B_Start(&g_dac_ctrl);
    /* Handle error */
    if (FSP_SUCCESS != err)
    {
        /* DAC start failure message */
        APP_ERR_RETURN(err,"\r\n** R_DAC_B_Start API failed **\r\n");
    }

    /* As mentioned in DAC properties and Electrical characteristics of User Manual (Section 68),
     * a software delay has to be given for stabilizing the voltage on DAC output pin.
     * Also referred as DAC conversion time delay */
    R_BSP_SoftwareDelay(STABILIZATION_DELAY, BSP_DELAY_UNITS_MILLISECONDS);

/*     Start the ADC scan in Single scan mode */
    err = R_ADC_B_ScanStart(&g_adc_ctrl);
    /* Handle error */
    if (FSP_SUCCESS != err)
    {
        /* ADC failure message */
        APP_ERR_RETURN(err,"\r\n** R_ADC_B_ScanStart API failed **\r\n");
    }
    /* Stop DAC conversion for consecutive the user input values */
    err = R_DAC_B_Stop(&g_dac_ctrl);
    /* Handle Error */
    if (FSP_SUCCESS != err)
    {
        /* DAC stop failure message */
        APP_ERR_RETURN(err,"\r\n** R_DAC_B_Stop API failed **\r\n");
    }
    return err;
}

/*******************************************************************************************************************//**
 * @brief       ADC callback function.
 * @param[in]   p_args
 * @retval      None
 **********************************************************************************************************************/
void g_adc_callback(adc_callback_args_t *p_args)
{
    if (ADC_EVENT_SCAN_COMPLETE == p_args->event)
    {
        fsp_err_t err = FSP_SUCCESS;     /* Error status */

        /* Read the result after ADC Scan is complete */
        err = R_ADC_B_Read(&g_adc_ctrl, ADC_CHANNEL, &g_adc_data);
        /* Handle error */
        if (FSP_SUCCESS != err)
        {
            g_error_flag = true;
        }
        else
        {
            g_is_read_complete = true;
        }
    }

    /* Check if calibration is complete and set flag */
    else if (ADC_EVENT_CALIBRATION_COMPLETE == p_args->event)
    {
        b_is_calibration_complete = true;
    }
    else
    {
        /* Do nothing */
    }
}

/*******************************************************************************************************************//**
 * @brief       This function closes opened DAC module before the project ends up in an error trap.
 * @param[IN]   None
 * @retval      None
 **********************************************************************************************************************/
static void dac_deinit(void)
{
    fsp_err_t err = FSP_SUCCESS;

    /* Close DAC module */
    err = R_DAC_B_Close(&g_dac_ctrl);
    /* Handle error */
    if (FSP_SUCCESS != err)
    {
        /* DAC Close failure message */
        APP_ERR_PRINT("\r\n** R_DAC_B_Close API failed **\r\n");
    }
}

/*******************************************************************************************************************//**
 * @brief       This function closes opened ADC module before the project ends up in an error trap.
 * @param[IN]   None
 * @retval      None
 **********************************************************************************************************************/
static void adc_deinit(void)
{
    fsp_err_t err = FSP_SUCCESS;

    /* Close ADC module */
    err = R_ADC_B_Close(&g_adc_ctrl);
    /* Handle error */
   if (FSP_SUCCESS != err)
   {
       /* ADC failure message */
       APP_ERR_PRINT("\r\n** R_ADC_B_Close API failed **\r\n");
   }
}

/*******************************************************************************************************************//**
 * This function is called at various points during the startup process. This implementation uses the event that is
 * called right before main() to set up the pins.
 *
 * @param[in]  event    Where at in the start up process the code is currently at
 **********************************************************************************************************************/
void R_BSP_WarmStart(bsp_warm_start_event_t event)
{
    if (BSP_WARM_START_RESET == event)
    {
#if BSP_FEATURE_FLASH_LP_VERSION != 0

        /* Enable reading from data flash */
        R_FACI_LP->DFLCTL = 1U;

        /* Would normally have to wait tDSTOP(6us) for data flash recovery. Placing the enable here, before clock and
         * C runtime initialization, should negate the need for a delay since the initialization will typically take
         * more than 6us */
#endif
    }

    if (BSP_WARM_START_POST_C == event)
    {
        /* C runtime environment and system clocks are setup */

        /* Configure pins */
        R_IOPORT_Open (&IOPORT_CFG_CTRL, &IOPORT_CFG_NAME);

#if BSP_CFG_SDRAM_ENABLED

        /* Setup SDRAM and initialize it. Must configure pins first */
        R_BSP_SdramInit(true);
#endif
    }
}

