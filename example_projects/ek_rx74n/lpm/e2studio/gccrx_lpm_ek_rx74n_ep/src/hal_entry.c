extern bsp_leds_t g_bsp_leds;

/*******************************************************************************************************************//**
 * main() is generated by the RX Configuration editor and is used to generate threads if an RTOS is used.  This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void hal_entry(void)
{
   fsp_err_t err = FSP_SUCCESS;
   fsp_pack_version_t version = {RESET_VALUE};

   /* Version get API for FLEX pack information */
   R_FSP_VersionGet (&version);
   R_IOPORT_PinWrite (&g_ioport_ctrl, (bsp_io_port_pin_t) g_bsp_leds.p_leds[ERR_LED],
                      (bsp_io_level_t) BSP_IO_LEVEL_LOW);
   #if (USE_VIRTUAL_COM == 1)
       err = (fsp_err_t) TERM_INIT();
       if (FSP_SUCCESS != err)
       {
           /* Turn ON error LED to indicate uart_init failed */
           R_IOPORT_PinWrite (&g_ioport_ctrl, (bsp_io_port_pin_t) g_bsp_leds.p_leds[ERR_LED],
                              (bsp_io_level_t) BSP_IO_LEVEL_HIGH);
           /* Error trap */
           ERROR_TRAP;
       }
   #endif

   /* Example Project information printed on the Console */
   APP_PRINT(BANNER_INFO, EP_VERSION, version.version_id_b.major, version.version_id_b.minor,
             version.version_id_b.patch);
   APP_PRINT(EP_INFO);

    /* Perform EP startup procedure */
    err = lpm_ep_startup();
    if (FSP_SUCCESS != err) {
        APP_ERR_PRINT("lpm_ep_startup Failed\r\n");
        APP_ERR_TRAP(err);
    }

    /* Perform EP main procedure */
    while (true)
    {
        err = lpm_ep_main_process();
            if (FSP_SUCCESS != err) {
                APP_ERR_PRINT("lpm_ep_main_process Failed\r\n");
                APP_ERR_TRAP(err);
            }
    }

}

/*******************************************************************************************************************//**
 * This function is called at various points during the startup process.  This implementation uses the event that is
 * called right before main() to set up the pins.
 *
 * @param[in]  event    Where at in the start up process the code is currently at
 **********************************************************************************************************************/
void R_BSP_WarmStart(bsp_warm_start_event_t event)
{
    if (BSP_WARM_START_RESET == event)
    {
#if BSP_FEATURE_FLASH_LP_VERSION != 0

        /* Enable reading from data flash. */
        R_FACI_LP->DFLCTL = 1U;

        /* Would normally have to wait tDSTOP(6us) for data flash recovery. Placing the enable here, before clock and
         * C runtime initialization, should negate the need for a delay since the initialization will typically take more than 6us. */
#endif
    }

    if (BSP_WARM_START_POST_C == event)
    {
        /* C runtime environment and system clocks are setup. */
        /* C runtime environment and system clocks are setup. */
#if (BSP_FEATURE_LPM_HAS_DEEP_STANDBY)
        if (R_SYSTEM->RSTSR0_b.DPSRSTF)
        {
            /* Perform internal reset procedure */
            source_internal_reset_handle();

            /* Clear DPSRSTF flag */
            R_SYSTEM->RSTSR0_b.DPSRSTF = 0;
        }
#endif
        /* Configure pins. */
        bsp_non_existent_port_init ();
        R_IOPORT_Open (&IOPORT_CFG_CTRL, &IOPORT_CFG_NAME);
    }
}

