/* Macro definition */

/* PVD0 detect reset value */
#define SYSTEM_RSTSR0_DETECT_PVD0_RESET        (1u)
#define SET_FLAG                               (1u)

/* PVD Example project details */
#define PVD_INFO     "\r\nThe example project demonstrates the typical use of the PVD HAL module APIs."\
                     "\r\nThe example project enables PVD0 circuit to reset MCU and PVD1 to generate maskable interrupt.\r\n"\
                     "\r\nPVD0 resets MCU only when input voltage drops below PVD0 threshold value."\
                     "\r\nTo detect this, user has to increase back the voltage value above PVD0 threshold value."\
                     "\r\nBy doing this, LED will turn ON indicating PVD0 reset detection."\
                     "\r\nEx: 2.8V is PVD0 threshold value, when input Voltage drops from 2.9V to 2.7V, PVD0 resets MCU."\
                     "\r\nUser has to rise input voltage above 2.8V again to detect PVD0 reset.\r\n"\
                     "\r\nPVD1 generates a maskable interrupt only when input voltage rises above PVD1 threshold value."\
                     "\r\nEx: 2.9V is PVD1 threshold value, when input voltage is raised from 2.8V to 3.0V,"\
                     "\r\nPVD1 generates the maskable interrupt.\r\n"

/* Macro to display instructions on how to run PVD EP */
#define PVD_NOTE   "\r\nNote:\
                   \r\n1. To run PVD Example project, use E2 Emulator Lite for debugging the code.\
                   \r\n2. To detect PVD0 Reset, input voltage has to be raised back above threshold value(Vdet0) once it is\
                   \r\ndropped below threshold value(Vdet0). This will turn ON LED and prints PVD0 reset detection message\
                   \r\non the Terminal Application.\r\n"

/* Define LED */
#define LED_RED         (IOPORT_PORT_06_PIN_04)

extern bsp_leds_t g_bsp_leds;
/* External Global Variables */
volatile uint8_t g_pvd1_status = RESET_VALUE;
volatile uint8_t g_pvd0_status = RESET_VALUE;

/* Function declarations */
void R_BSP_WarmStart(bsp_warm_start_event_t event);

/* Private function declarations */
static fsp_err_t check_reset_status(void);

/*******************************************************************************************************************//**
 * main() is generated by the RX Configuration editor and is used to generate threads if an RTOS is used.  This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void hal_entry(void)
{
    fsp_pack_version_t version = {RESET_VALUE};
    fsp_err_t err = FSP_SUCCESS;                    /* Error status */
    fsp_err_t PVD_err = FSP_SUCCESS;

    /* Version get API for FLEX pack information */
    R_FSP_VersionGet(&version);
    R_IOPORT_PinWrite (&g_ioport_ctrl, (bsp_io_port_pin_t) g_bsp_leds.p_leds[ERR_LED],
                       (bsp_io_level_t) BSP_IO_LEVEL_LOW);
#if (USE_VIRTUAL_COM == 1)
    err = (fsp_err_t) TERM_INIT();
    if (FSP_SUCCESS != err)
    {
        /* Turn ON error LED to indicate uart_init failed */
        R_IOPORT_PinWrite (&g_ioport_ctrl, (bsp_io_port_pin_t) g_bsp_leds.p_leds[ERR_LED],
                           (bsp_io_level_t) BSP_IO_LEVEL_HIGH);
        /* Error trap */
        ERROR_TRAP;
    }
#endif
    /* Example Project information printed on the Console */
    APP_PRINT (BANNER_INFO, EP_VERSION, version.version_id_b.major, version.version_id_b.minor, version.version_id_b.patch);

    APP_PRINT(PVD_INFO);

    APP_PRINT(PVD_NOTE);

    /* Open PVD0 instance to detect Voltage */
    err = R_PVD_Open(&g_pvd0_ctrl, &g_pvd0_cfg);
    if (FSP_SUCCESS != err)
    {
        /* Print Error on Terminal Application */
        APP_ERR_PRINT ("\r\n ** R_PVD_Open API failed ** \r\n");
        APP_ERR_TRAP (err);
    }

    /* Open PVD1 instance to detect Voltage rise above threshold value by generating an maskable interrupt */
    err = R_PVD_Open(&g_pvd_ctrl, &g_pvd_cfg);
    if (FSP_SUCCESS != err)
    {
        /* Print Error on Terminal Application */
        APP_ERR_PRINT ("\r\n ** R_PVD_Open API failed ** \r\n");
        APP_ERR_TRAP (err);
    }

    APP_PRINT ("\r\nPVD1 Enabled to generate a maskable interrupt when Voltage raises above the threshold value\r\n");

    while(true)
    {
        /* Check if reset is caused by PVD0 monitor */
        err = check_reset_status();
        if (FSP_SUCCESS != err)
        {
            /* Print Error on Terminal Application */
            APP_ERR_PRINT ("\r\n ** Unable to turn LED on ** \r\n");
            APP_ERR_TRAP (err);
        }

        /* Check If Voltage increased than threshold value. If yes, notify user */
        if(SET_FLAG == g_pvd1_status)
        {
            APP_PRINT ("\r\nVoltage Raised above threshold value.");

            /* Clear PVD1 Status */
            err = R_PVD_StatusClear(&g_pvd_ctrl);
            if (FSP_SUCCESS != err)
            {
                /* Print Error on Terminal Application */
                APP_ERR_PRINT ("\r\n ** R_PVD_StatusClear API failed ** \r\n");

                /* Close PVD1 driver */
                PVD_err = R_PVD_Close(&g_pvd_ctrl);
                if (FSP_SUCCESS != PVD_err)
                {
                    APP_ERR_PRINT ("\r\n ** R_PVD_Close API failed ** \r\n");
                }
                APP_ERR_TRAP (err);
            }

            APP_PRINT ("\r\nPVD1 Status flag is Cleared.\r\n");
            g_pvd1_status = RESET_VALUE;
        }
    }
}

/*******************************************************************************************************************//**
 * @brief    Check if reset caused by PVD0 or not. If yes, Turn LED ON.
 * @param[IN]   None
 * @retval      None
 **********************************************************************************************************************/
static fsp_err_t check_reset_status(void)
{
    fsp_err_t io_err = FSP_SUCCESS;
    /* Check if reset was caused by the PVD0? If it was, turn on LED to indicate PVD0 reset triggered. */
    if (g_pvd0_status == SET_FLAG)
    {
        /* Clear the flag once read the value */
        R_SYSTEM->RSTSR0_b.PVD0RF = RESET_VALUE;

        /* Notify user that reset is caused by PVD0 monitor */
        APP_PRINT ("\r\n************************ PVD0 Reset detected ************************\r\n");

        /* Turn ON LED */
        io_err = R_IOPORT_PinWrite (&g_ioport_ctrl, (bsp_io_port_pin_t) LED_RED, BSP_IO_LEVEL_HIGH);
        if (FSP_SUCCESS != io_err)
        {
            /* Print Error on Terminal Application */
            APP_ERR_PRINT ("\r\n ** R_IOPORT_PinWrite API failed ** \r\n");
        }

        /* PVD0 Status flag is Cleared. */
        g_pvd0_status = RESET_VALUE;
    }
    return io_err;
}

/*******************************************************************************************************************//**
 * @brief This function is callback for r_PVD1 instance and notifies user about rise in Voltage level.
 * @param[in]   p_args   PVD callback parameters
 * @retval      None
 **********************************************************************************************************************/
void pvd1_callback(voltage_detection_callback_args_t *p_args)
{

    /* Voltage Raising detected */
    if(VOLTAGE_DETECTION_CURRENT_STATE_ABOVE_THRESHOLD == p_args->current_state)
    {
        /* Set the PVD1 status flag to notify the user about rise in voltage */
        g_pvd1_status = SET_FLAG;
    }
}

/*******************************************************************************************************************//**
 * @brief This function is callback for r_PVD0 instance and notifies user about rise in Voltage level.
 * @param[in]   p_args   PVD callback parameters
 * @retval      None
 **********************************************************************************************************************/
void pvd0_callback(voltage_detection_callback_args_t *p_args)
{
    FSP_PARAMETER_NOT_USED(p_args);

    if (SYSTEM_RSTSR0_DETECT_PVD0_RESET == R_SYSTEM->RSTSR0_b.PVD0RF)
    {
        /* Set the PVD0 status flag to notify the user about rise in voltage */
        g_pvd0_status = SET_FLAG;

    }
}

/*******************************************************************************************************************//**
 * This function is called at various points during the startup process.  This implementation uses the event that is
 * called right before main() to set up the pins.
 *
 * @param[in]  event    Where at in the start up process the code is currently at
 **********************************************************************************************************************/
void R_BSP_WarmStart(bsp_warm_start_event_t event)
{
    if (BSP_WARM_START_RESET == event)
    {
#if BSP_FEATURE_FLASH_LP_VERSION != 0

        /* Enable reading from data flash. */
        R_FACI_LP->DFLCTL = 1U;

        /* Would normally have to wait tDSTOP(6us) for data flash recovery. Placing the enable here, before clock and
         * C runtime initialization, should negate the need for a delay since the initialization will typically take more than 6us. */
#endif
    }

    if (BSP_WARM_START_POST_C == event)
    {
        /* C runtime environment and system clocks are setup. */

        /* Configure pins. */
        R_IOPORT_Open (&IOPORT_CFG_CTRL, &IOPORT_CFG_NAME);
    }
}

